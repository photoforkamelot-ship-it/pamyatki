// Мелкие помощники: создание элементов, даты, форматирование.

export function h(tag, attrs, ...children) {
  const node = document.createElement(tag);
  if (attrs) {
    for (const [k, v] of Object.entries(attrs)) {
      if (v === undefined || v === null || v === false) continue;
      if (k === 'class') node.className = v;
      else if (k === 'style' && typeof v === 'object') Object.assign(node.style, v);
      else if (k.startsWith('on') && typeof v === 'function') node.addEventListener(k.slice(2).toLowerCase(), v);
      else if (k === 'html') node.innerHTML = v;
      else if (v === true) node.setAttribute(k, '');
      else if (k in node && typeof v !== 'string') node[k] = v;
      else node.setAttribute(k, v);
    }
  }
  append(node, children);
  return node;
}

function append(node, children) {
  for (const c of children) {
    if (c === null || c === undefined || c === false) continue;
    if (Array.isArray(c)) append(node, c);
    else if (c instanceof Node) node.appendChild(c);
    else node.appendChild(document.createTextNode(String(c)));
  }
}

export const uid = () => Math.random().toString(36).slice(2, 9) + Date.now().toString(36).slice(-4);

export function fmtDate(d) {
  if (!d) return '';
  const x = new Date(d);
  return x.toLocaleDateString('ru-RU', { day: '2-digit', month: '2-digit', year: 'numeric' });
}

export function fmtDateTime(d) {
  if (!d) return '';
  const x = new Date(d);
  return x.toLocaleString('ru-RU', { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}

export function monthKey(d) {
  const x = new Date(d);
  return x.toLocaleDateString('ru-RU', { month: 'long', year: 'numeric' });
}

export function todayISO() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function fmtSize(bytes) {
  if (!bytes && bytes !== 0) return '';
  if (bytes < 1024) return bytes + ' Б';
  if (bytes < 1024 * 1024) return Math.round(bytes / 1024) + ' КБ';
  return (bytes / 1024 / 1024).toFixed(1).replace('.', ',') + ' МБ';
}

export function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}

export const pages = (n) => `${n} ${plural(n, 'страница', 'страницы', 'страниц')}`;

export function shortFio(fio) {
  if (!fio) return '';
  const parts = fio.trim().split(/\s+/);
  if (parts.length === 1) return parts[0];
  const [f, i, o] = parts;
  return `${f} ${i ? i[0] + '.' : ''}${o ? o[0] + '.' : ''}`;
}

export function surnameName(fio) {
  if (!fio) return '';
  const parts = fio.trim().split(/\s+/);
  return parts.slice(0, 2).join(' ');
}

export function surname(fio) {
  return (fio || '').trim().split(/\s+/)[0] || '';
}

export function debounce(fn, ms) {
  let t;
  return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
}

export function baseName(filename) {
  return filename.replace(/\.[^.]+$/, '').replace(/[_]+/g, ' ').trim();
}

export function money(v) {
  if (v === '' || v === null || v === undefined || isNaN(Number(v))) return '';
  return Number(v).toLocaleString('ru-RU') + ' ₽';
}

export function bytesToBase64(bytes) {
  let s = '';
  const chunk = 0x8000;
  for (let i = 0; i < bytes.length; i += chunk) {
    s += String.fromCharCode.apply(null, bytes.subarray(i, i + chunk));
  }
  return btoa(s);
}

export function base64ToBytes(b64) {
  const s = atob(b64);
  const out = new Uint8Array(s.length);
  for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i);
  return out;
}

export function clone(o) {
  return JSON.parse(JSON.stringify(o));
}

